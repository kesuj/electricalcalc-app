"""PDF and Markdown engineering report generation from saved CalcResults.

Reports always carry a review status. The software never marks a report as certified,
approved or stamped; "Reviewed" status only records the reviewer name the user typed.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from fpdf import FPDF
from fpdf.enums import XPos, YPos
from fpdf.fonts import FontFace

from . import __version__, config
from .calc.result import CalcResult

REVIEW_STATUSES = ("DRAFT - not reviewed", "Under review", "Reviewed by engineer (see reviewer)")
DISCLAIMER = (
    "This is a preliminary calculation report generated by software. It is not a certified, approved or "
    "stamped engineering design and must not be used for construction or procurement without review by a "
    "qualified engineer against site conditions, manufacturer data and the applicable local codes and "
    "regulations. Results are only as reliable as the inputs and assumptions listed.")

_FONT_CANDIDATES = [
    ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    ("/Library/Fonts/Arial Unicode.ttf", "/Library/Fonts/Arial Unicode.ttf"),
]
_ASCII = {"²": "2", "³": "3", "√": "sqrt", "φ": "phi", "Ω": "ohm", "µ": "u", "°": " deg", "×": "x",
          "−": "-", "≈": "~", "η": "eta", "α": "alpha", "Δ": "d", "·": "*", "–": "-", "—": "-", "→": "->",
          "≤": "<=", "≥": ">="}


@dataclass
class ReportMeta:
    project_name: str
    client: str = ""
    location: str = ""
    prepared_by: str = ""
    review_status: str = REVIEW_STATUSES[0]
    reviewer: str = ""
    notes: str = ""
    is_demo: bool = False
    report_date: str = field(default_factory=lambda: date.today().isoformat())


def _fmt(q) -> str:
    v = q["value"]
    if isinstance(v, float):
        v = f"{v:,.2f}" if abs(v) >= 100 else f"{v:,.4g}"
    return f"{v} {q['unit']}".strip()


class _PDF(FPDF):
    def __init__(self, title: str, demo: bool):
        super().__init__(format="A4")
        self.doc_title, self.demo = title, demo
        self.unicode = False
        for reg, bold in _FONT_CANDIDATES:
            if Path(reg).exists() and Path(bold).exists():
                self.add_font("Body", "", reg)
                self.add_font("Body", "B", bold)
                self.unicode = True
                break
        self.family = "Body" if self.unicode else "Helvetica"
        self.set_auto_page_break(True, margin=18)
        self.set_margins(16, 16, 16)

    def t(self, s: str) -> str:
        if self.unicode:
            return s
        for k, v in _ASCII.items():
            s = s.replace(k, v)
        return s.encode("latin-1", "replace").decode("latin-1")

    def header(self):
        self.set_font(self.family, "B", 9)
        self.set_text_color(90, 90, 90)
        self.cell(0, 6, self.t(f"{config.APP_NAME} - {self.doc_title}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        if self.demo:
            self.set_text_color(180, 40, 40)
            self.cell(0, 5, "DEMONSTRATION DATA - NOT A REAL PROJECT", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(30, 90, 160)
        self.line(16, self.get_y() + 1, 194, self.get_y() + 1)
        self.ln(4)
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-13)
        self.set_font(self.family, "", 7.5)
        self.set_text_color(110, 110, 110)
        self.cell(0, 5, self.t(f"Preliminary - not for construction | {config.APP_NAME} v{__version__} | "
                               f"Page {self.page_no()}/{{nb}}"), align="C")

    def h1(self, s):
        self.set_font(self.family, "B", 16); self.set_text_color(20, 60, 120)
        self.multi_cell(0, 8, self.t(s), new_x=XPos.LMARGIN, new_y=YPos.NEXT); self.set_text_color(0, 0, 0)

    def h2(self, s):
        self.ln(2); self.set_font(self.family, "B", 12); self.set_text_color(20, 60, 120)
        self.multi_cell(0, 7, self.t(s), new_x=XPos.LMARGIN, new_y=YPos.NEXT); self.set_text_color(0, 0, 0)

    def h3(self, s):
        self.set_font(self.family, "B", 10)
        self.multi_cell(0, 6, self.t(s), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def para(self, s, size=9.5):
        self.set_font(self.family, "", size)
        self.multi_cell(0, 5, self.t(s), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def bullets(self, items):
        self.set_font(self.family, "", 9)
        for it in items:
            self.multi_cell(0, 5, self.t(f"-  {it}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def kv_table(self, rows: list[tuple[str, str]]):
        self.set_font(self.family, "", 9)
        with self.table(col_widths=(95, 83), text_align=("LEFT", "RIGHT"), line_height=5.5,
                        first_row_as_headings=False, borders_layout="HORIZONTAL_LINES") as tbl:
            for a, b in rows:
                r = tbl.row(); r.cell(self.t(a)); r.cell(self.t(b))

    def grid(self, rows: list[dict]):
        if not rows:
            return
        cols = list(rows[0].keys())
        self.set_font(self.family, "", 8)
        heading = FontFace(emphasis="BOLD", fill_color=(225, 235, 248))
        with self.table(line_height=5, headings_style=heading, text_align="LEFT") as tbl:
            h = tbl.row()
            for c in cols:
                h.cell(self.t(str(c)))
            for row in rows:
                r = tbl.row()
                for c in cols:
                    r.cell(self.t(str(row.get(c, ""))))


def build_pdf(meta: ReportMeta, results: list[dict], ai_commentary: str | None = None) -> bytes:
    """results: list of CalcResult.to_dict() items. ai_commentary is printed in a separately
    labelled section so calculated values are never mixed with AI text."""
    if not results:
        raise ValueError("At least one saved calculation is required to build a report.")
    pdf = _PDF(meta.project_name, meta.is_demo)
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.h1("Preliminary Engineering Calculation Report")
    pdf.kv_table([("Project", meta.project_name), ("Client", meta.client or "-"), ("Location", meta.location or "-"),
                  ("Prepared by", meta.prepared_by or "-"), ("Report date", meta.report_date),
                  ("Software", f"{config.APP_NAME} v{__version__}"), ("Review status", meta.review_status),
                  ("Reviewer", meta.reviewer or "Not reviewed")])
    pdf.ln(2)
    pdf.set_fill_color(255, 244, 229)
    pdf.set_font(pdf.family, "", 8.5)
    pdf.multi_cell(0, 4.6, pdf.t(DISCLAIMER), fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    if meta.notes:
        pdf.h2("Scope and notes"); pdf.para(meta.notes)
    pdf.h2("Contents")
    pdf.bullets([f"{i}. {r['name']}" for i, r in enumerate(results, 1)])

    for i, r in enumerate(results, 1):
        pdf.add_page()
        pdf.h2(f"{i}. {r['name']}")
        pdf.h3("Input parameters")
        pdf.kv_table([(q["label"] or k, _fmt(q)) for k, q in r["inputs"].items()])
        pdf.h3("Calculation method and equations")
        pdf.bullets(r["equations"])
        pdf.h3("Results (calculated by deterministic code)")
        pdf.kv_table([(q["label"] or k, _fmt(q)) for k, q in r["outputs"].items()])
        for tname, rows in r.get("tables", {}).items():
            pdf.h3(tname); pdf.grid(rows)
        if r["assumptions"]:
            pdf.h3("Assumptions"); pdf.bullets(r["assumptions"])
        if r["warnings"]:
            pdf.h3("Warnings and limitations"); pdf.bullets(r["warnings"])
        if r["references"]:
            pdf.h3("Data sources and references"); pdf.bullets(r["references"])

    if ai_commentary:
        pdf.add_page()
        pdf.h2("AI-generated commentary (not part of the calculation)")
        pdf.para("The text below was written by an AI model from the calculated results above. It may contain "
                 "errors and has no engineering authority; the calculated values take precedence.", 8.5)
        pdf.ln(1); pdf.para(ai_commentary)

    pdf.add_page()
    pdf.h2("Review record")
    pdf.para("To be completed by the reviewing engineer. Signing below records review only; it does not by itself "
             "constitute certification under any jurisdiction's professional engineering rules.")
    pdf.kv_table([("Reviewed by", meta.reviewer or ""), ("Registration / licence no.", ""), ("Signature", ""),
                  ("Date", ""), ("Comments", "")])
    return bytes(pdf.output())


def build_markdown(meta: ReportMeta, results: list[dict], ai_commentary: str | None = None) -> str:
    """Editable plain-text version of the same report."""
    lines = [f"# Preliminary Engineering Calculation Report - {meta.project_name}", ""]
    if meta.is_demo:
        lines += ["> **DEMONSTRATION DATA - NOT A REAL PROJECT**", ""]
    lines += [f"- Client: {meta.client or '-'}", f"- Location: {meta.location or '-'}",
              f"- Prepared by: {meta.prepared_by or '-'}", f"- Date: {meta.report_date}",
              f"- Software: {config.APP_NAME} v{__version__}", f"- Review status: {meta.review_status}",
              f"- Reviewer: {meta.reviewer or 'Not reviewed'}", "", f"> {DISCLAIMER}", ""]
    for i, r in enumerate(results, 1):
        lines += [f"## {i}. {r['name']}", "", "### Inputs", "", "| Parameter | Value |", "|---|---|"]
        lines += [f"| {q['label'] or k} | {_fmt(q)} |" for k, q in r["inputs"].items()]
        lines += ["", "### Method", ""] + [f"- `{e}`" for e in r["equations"]]
        lines += ["", "### Results", "", "| Result | Value |", "|---|---|"]
        lines += [f"| {q['label'] or k} | {_fmt(q)} |" for k, q in r["outputs"].items()]
        for tname, rows in r.get("tables", {}).items():
            if rows:
                cols = list(rows[0])
                lines += ["", f"### {tname}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
                lines += ["| " + " | ".join(str(row.get(c, "")) for c in cols) + " |" for row in rows]
        for title, key in (("Assumptions", "assumptions"), ("Warnings and limitations", "warnings"),
                           ("References", "references")):
            if r[key]:
                lines += ["", f"### {title}", ""] + [f"- {x}" for x in r[key]]
        lines.append("")
    if ai_commentary:
        lines += ["## AI-generated commentary (not part of the calculation)", "", ai_commentary, ""]
    return "\n".join(lines)


def result_dicts(results: list[CalcResult]) -> list[dict]:
    return [r.to_dict() for r in results]
